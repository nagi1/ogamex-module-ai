        static void AuthorExchanges(CommeillFautAsset cif)
        {
            foreach (var x in Exchanges())
            {
                cif.AddOrUpdateExchange(new SocialExchangeDTO
                {
                    Name = Name.BuildName(x.Name),
                    Description = x.Description,
                    Steps = "Start, End",
                    Target = Name.BuildName("[x]"), // must be a variable (README, CiF constraint 1)
                    StartingConditions = new ConditionSetDTO { ConditionSet = x.Start },
                    InfluenceRules = x.Rules.Select(r => new InfluenceRuleDTO
                    {
                        Rule = new ConditionSetDTO { ConditionSet = r.Item2 },
                        Value = r.Item1,
                        Mode = Name.BuildName("*"),
                    }).ToList(),
                });
            }
            cif.Save();
        }

        // Layer `Exchange`: FAtiMA's decision making ranks the exchanges by their CiF volition for the focused player.
        static void AuthorExchangeDecisions(EmotionalDecisionMaking.EmotionalDecisionMakingAsset edm)
        {
            foreach (var x in Exchanges())
            {
                edm.AddActionRule(new ActionRuleDTO
                {
                    Action = Name.BuildName($"Exchange({x.Name})"),
                    Target = Name.BuildName("[x]"),
                    Priority = Name.BuildName("[v]"),
                    Layer = Name.BuildName("Exchange"),
                    Conditions = new ConditionSetDTO { ConditionSet = new[] { "Focus(SELF) = [x]", $"Volition({x.Name}, Start, [x], *) = [v]" } },
                });
            }
        }

        // Social importance of the other player: what the relationship is worth keeping (the "future" term).
        static void AuthorSocialImportance(SocialImportanceAsset si)
        {
            void A(string description, int value, params string[] conditions) =>
                si.AddAttributionRule(new AttributionRuleDTO
                {
                    Description = description,
                    Target = Name.BuildName("[x]"),
                    Value = Name.BuildName(value.ToString(CultureInfo.InvariantCulture)),
                    Conditions = new ConditionSetDTO { ConditionSet = conditions },
                });

            A("respected", 3, "Respect(SELF, [x]) >= 0.6");
            A("trusted", 3, "Trust(SELF, [x]) >= 0.6");
            A("owed", 2, "Debt(SELF, [x]) >= 0.4");
            A("liked", 2, "Liking(SELF, [x]) >= 0.6");
            A("powerful", 3, "Power(SELF, [x]) >= 1.5");
            A("partner", 2, "Pact(SELF, [x]) = True");
            A("feared", 1, "Fear(SELF, [x]) >= 0.6");
            si.Save();
        }
