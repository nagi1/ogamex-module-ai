    // Authors the OGameX social scenario set (SOCIAL-ENGINES-CONTRACT.md: /social/appraise, /social/exchange)
    // through the real FAtiMA APIs, one scenario per archetype of resources/behavior/social-persona.yaml.
    //
    // Everything that makes a persona feel differently is FAtiMA data, evaluated by the toolkit at run time:
    //  - OCC appraisal rules whose Desirability / Praiseworthiness / Like / Goal Success Probability are computed
    //    in rule conditions (KB `Math`) from the persona's 12 traits (beliefs `Trait(SELF, <Trait>)`), the
    //    relationship beliefs towards the actor (`Trust/Liking/Fear/Respect/Debt(SELF, [x])`) and the size of
    //    the visible event (`Magnitude(SELF, [x])`);
    //  - per-archetype emotion dispositions (decay rate and threshold per OCC emotion), so a vindictive
    //    persona's Anger and Hate outlive a forgiving one's under the toolkit's own half-life decay;
    //  - a per-archetype goal Safe(SELF) whose significance (from courage) turns threats into Fear. One goal
    //    only: the toolkit keys an active emotion by its cause and appraisal-variable names, so two goal
    //    probabilities on one event collapse into a single Fear;
    //  - decision rules (layer `Belief`) that move the relationship beliefs after each event;
    //  - Comme il Faut social exchanges whose volition sums trait, relationship, emotion, context and
    //    social-importance (SI) influence rules, and decision rules (layer `Exchange`) that rank them.
    //
    // Usage: SocialSeeder <social-persona.yaml> <outputFile>
    class Program
    {
        const string GSP = "Goal Success Probablity"; // the toolkit's spelling, part of its serialized contract

        static readonly string[] Relations = { "Trust", "Liking", "Fear", "Respect", "Debt" };

        // Contract event -> perceived action name.
        static readonly (string Event, string Action)[] Events =
        {
            ("betrayed", "Betray"), ("helped", "Aid"), ("attacked", "Attack"), ("threatened", "Threaten"),
            ("pact_offered", "OfferPact"), ("pact_kept", "KeepPact"), ("tribute_demanded", "DemandTribute"),
            ("coup", "Coup"), ("leak_heard", "Leak"),
        };

        static void Main(string[] args)
        {
            var yamlPath = args.Length > 0 ? args[0] : "social-persona.yaml";
            var outFile = args.Length > 1 ? args[1] : "ogame-social.json";

            var (traitNames, archetypes) = ReadPersonas(File.ReadAllText(yamlPath));

            var personas = new JsonObject();
            var archetypeTable = new JsonObject();
            foreach (var (name, traits) in archetypes)
            {
                var t = traitNames.Select((n, i) => (n, traits[i])).ToDictionary(p => p.n, p => p.Item2);
                var (scenario, assets) = AuthorPersona(name, t);
                personas[name] = new JsonObject
                {
                    ["character"] = Pascal(name),
                    ["scenario"] = JsonNode.Parse(scenario),
                    ["assets"] = JsonNode.Parse(assets),
                };
                archetypeTable[name] = new JsonArray(traits.Select(v => (JsonNode)JsonValue.Create(v)).ToArray());
            }

            var bundle = new JsonObject
            {
                ["name"] = "OgameSocial",
                ["description"] = "OGameX social appraisal and social exchanges (generated by Applications/SocialSeeder from social-persona.yaml)",
                ["traits"] = new JsonArray(traitNames.Select(n => (JsonNode)JsonValue.Create(n)).ToArray()),
                ["relations"] = new JsonArray(Relations.Select(n => (JsonNode)JsonValue.Create(n.ToLowerInvariant())).ToArray()),
                ["events"] = new JsonObject(Events.Select(e => new KeyValuePair<string, JsonNode>(e.Event, JsonValue.Create(e.Action)))),
                ["exchanges"] = new JsonArray(Exchanges().Select(x => (JsonNode)JsonValue.Create(x.Name)).ToArray()),
                ["archetypes"] = archetypeTable,
                ["personas"] = personas,
            };

            File.WriteAllText(outFile, bundle.ToJsonString(new JsonSerializerOptions { WriteIndented = false }));
            Console.WriteLine($"Wrote {archetypes.Count} personas to {Path.GetFullPath(outFile)}");
        }

        // ------------------------------------------------------------------ persona data

        static (List<string>, List<(string, float[])>) ReadPersonas(string yaml)
        {
            var lines = yaml.Split('\n');
            var traits = new List<string>();
            var archetypes = new List<(string, float[])>();
            string section = null;
            foreach (var raw in lines)
            {
                var line = raw.TrimEnd('\r');
                if (Regex.IsMatch(line, @"^\w+:")) { section = line.Split(':')[0]; continue; }
                if (section == "traits")
                {
                    var m = Regex.Match(line, @"^\s+(\w+):");
                    if (m.Success) traits.Add(m.Groups[1].Value);
                }
                if (section == "archetypes")
                {
                    var m = Regex.Match(line, @"^\s+(\w+):\s*\{.*traits:\s*\[([^\]]+)\]");
                    if (m.Success)
                        archetypes.Add((m.Groups[1].Value, m.Groups[2].Value.Split(',')
                            .Select(v => float.Parse(v.Trim(), CultureInfo.InvariantCulture)).ToArray()));
                }
            }
            if (traits.Count != 12 || archetypes.Count == 0)
                throw new InvalidDataException($"social-persona.yaml: {traits.Count} traits, {archetypes.Count} archetypes");
            return (traits, archetypes);
        }

        static string Pascal(string snake) =>
            string.Concat(snake.Split('_').Select(p => char.ToUpperInvariant(p[0]) + p.Substring(1)));

        static string Cap(string s) => char.ToUpperInvariant(s[0]) + s.Substring(1);

        static string F(float v) => v.ToString("0.###", CultureInfo.InvariantCulture);

        static int Clamp(double v, int lo, int hi) => (int)Math.Max(lo, Math.Min(hi, Math.Round(v)));

        // ------------------------------------------------------------------ expression -> FAtiMA conditions

        // Builds a chain of KB conditions that computes a value with the toolkit's own `Math` dynamic property.
        // Each step binds a fresh variable; the result variable is then used as an appraisal value, an action
        // argument or a priority. Nothing is computed here: the conditions are evaluated by FAtiMA.
        class Expr
        {
            readonly List<string> conds = new List<string>();
            int n;
            readonly string p;
            public Expr(string prefix) { p = prefix; }
            public IEnumerable<string> Conditions => conds;
            string Fresh() => $"[{p}{n++}]";
            public string Bind(string property) { var v = Fresh(); conds.Add($"{property} = {v}"); return v; }
            public string Lit(float value) { var v = Fresh(); conds.Add($"Math({F(value)}, Plus, 0) = {v}"); return v; }
            public string Op(string a, string op, string b) { var v = Fresh(); conds.Add($"Math({a}, {op}, {b}) = {v}"); return v; }
            public string Mul(string a, float k) => Op(a, "Times", F(k));
            public string Add(string a, float k) => Op(a, "Plus", F(k));
            public void Raw(string condition) => conds.Add(condition);

            // base + sum(w_i * term_i), every term a bound variable.
            public string Linear(float @base, params (float W, string Term)[] terms)
            {
                string acc = null;
                foreach (var (w, term) in terms)
                {
                    var wt = Mul(term, w);
                    acc = acc == null ? wt : Op(acc, "Plus", wt);
                }
                return acc == null ? Lit(@base) : Add(acc, @base);
            }
        }

        static string Trait(string t) => $"Trait(SELF, {Cap(t)})";
        static string Rel(string r) => $"{r}(SELF, [x])";

        // ------------------------------------------------------------------ authoring

        static (string, string) AuthorPersona(string archetype, Dictionary<string, float> t)
        {
            var iat = new IntegratedAuthoringToolAsset
            {
                ScenarioName = "OgameSocial" + Pascal(archetype),
                ScenarioDescription = $"OGameX social persona '{archetype}': OCC appraisal, relationship beliefs and CiF exchanges",
            };
            var assets = new AssetStorage();
            iat.Assets = assets;

            AuthorExchanges(CommeillFautAsset.CreateInstance(assets));
            AuthorSocialImportance(SocialImportanceAsset.CreateInstance(assets));

            var character = Pascal(archetype);
            iat.AddNewCharacter((Name)character);
            var rpc = iat.Characters.First(c => c.CharacterName == (Name)character);
            rpc.LoadAssociatedAssets(assets);
            rpc.Mood = 0;

            // Prospect-based emotions need goals: Fear is (1 - likelihood) x significance.
            rpc.AddOrUpdateGoal(new GoalDTO { Name = "Safe(SELF)", Significance = 1 + 9 * (1 - t["courage"]), Likelihood = 1 });

            var ea = rpc.m_emotionalAppraisalAsset;
            AuthorDispositions(ea, t);
            AuthorAppraisal(ea);
            ea.Save();

            var edm = rpc.m_emotionalDecisionMakingAsset;
            AuthorRelationshipUpdates(edm);
            AuthorExchangeDecisions(edm);
            edm.Save();

            return (iat.ToJson(), assets.ToJson());
        }

        // Emotion dispositions: decay rate (1 = slowest, the toolkit's half-life multiplier) and threshold.
        static void AuthorDispositions(EmotionalAppraisal.EmotionalAppraisalAsset ea, Dictionary<string, float> t)
        {
            var grudge = t["forgiveness"] * (1 - t["vindictiveness"]);
            void D(string emotion, int decay, int threshold) =>
                ea.AddEmotionDisposition(new EmotionDispositionDTO { Emotion = emotion, Decay = decay, Threshold = threshold });

            ea.DefaultEmotionDisposition = new EmotionDispositionDTO { Emotion = "*", Decay = 3, Threshold = 0 };
            D("Anger", Clamp(1 + 9 * grudge, 1, 10), 0);
            D("Hate", Clamp(1 + 7 * grudge, 1, 10), 0);
            D("Reproach", Clamp(1 + 6 * t["forgiveness"], 1, 10), 0);
            D("Fear", Clamp(1 + 6 * t["courage"], 1, 10), Clamp(2 * t["courage"], 0, 2));
            D("Gratitude", Clamp(1 + 6 * (1 - t["loyalty"]), 1, 10), 0);
            D("Love", Clamp(1 + 6 * (1 - t["loyalty"]), 1, 10), 0);
            D("Admiration", Clamp(1 + 4 * (1 - t["authority"]), 1, 10), 0);
            D("Distress", Clamp(1 + 5 * t["courage"], 1, 10), 0);
        }

        // One appraisal rule per visible event. Values are on FAtiMA's 0..10 scale.
        static void AuthorAppraisal(EmotionalAppraisal.EmotionalAppraisalAsset ea)
        {
            void Rule(string action, Action<Expr, List<AppraisalVariableDTO>> body)
            {
                var e = new Expr("v");
                var vars = new List<AppraisalVariableDTO>();
                body(e, vars);
                ea.AddOrUpdateAppraisalRule(new AppraisalRuleDTO
                {
                    EventMatchingTemplate = Name.BuildName($"Event(Action-End, [x], {action}, SELF)"),
                    AppraisalVariables = new EmotionalAppraisal.AppraisalVariables(vars),
                    Conditions = new ConditionSetDTO { ConditionSet = e.Conditions.ToArray() },
                });
            }
            AppraisalVariableDTO V(string name, string value, string target) =>
                new AppraisalVariableDTO { Name = name, Value = Name.BuildName(value), Target = Name.BuildName(target) };

            // scale(m, k, base, terms): k * m * (base + sum w*term). Negative k for undesirable / blameworthy.
            string Scaled(Expr e, string m, float k, float @base, params (float, string)[] terms) =>
                e.Op(e.Mul(e.Linear(@base, terms), k), "Times", m);

            Rule("Betray", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust")); var liking = e.Bind(Rel("Liking")); var fear = e.Bind(Rel("Fear"));
                var loyalty = e.Bind(Trait("loyalty")); var honesty = e.Bind(Trait("honesty"));
                var vind = e.Bind(Trait("vindictiveness")); var courage = e.Bind(Trait("courage"));
                // A friend's betrayal hurts more than a stranger's: desirability scales with trust and liking.
                v.Add(V("Desirability", Scaled(e, m, -10, 0.2f, (0.5f, trust), (0.3f, liking)), "-"));
                // Blame follows the judge's own code of honour.
                v.Add(V("Praiseworthiness", Scaled(e, m, -10, 0.2f, (0.4f, loyalty), (0.4f, honesty)), "[x]"));
                v.Add(V("Like", Scaled(e, m, -10, 0.1f, (0.6f, vind), (0.3f, trust)), "-"));
                v.Add(V(GSP, Scaled(e, m, -0.3f, 0.3f, (0.4f, fear), (-0.3f, courage)), "Safe(SELF)"));
            });

            Rule("Aid", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust")); var liking = e.Bind(Rel("Liking"));
                var loyalty = e.Bind(Trait("loyalty")); var generosity = e.Bind(Trait("generosity"));
                var cunning = e.Bind(Trait("cunning"));
                v.Add(V("Desirability", Scaled(e, m, 10, 0.4f, (0.3f, liking), (0.3f, generosity)), "-"));
                // A cunning mind discounts the merit of a gift (it suspects a motive); a loyal one honours it.
                v.Add(V("Praiseworthiness", Scaled(e, m, 10, 0.3f, (0.5f, loyalty), (-0.3f, cunning), (0.2f, trust)), "[x]"));
                v.Add(V("Like", Scaled(e, m, 10, 0.2f, (0.4f, trust), (0.4f, generosity)), "-"));
                v.Add(V(GSP, Scaled(e, m, 0.3f, 1f), "Safe(SELF)"));
            });

            Rule("Attack", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust")); var fear = e.Bind(Rel("Fear"));
                var cruelty = e.Bind(Trait("cruelty")); var vind = e.Bind(Trait("vindictiveness"));
                var courage = e.Bind(Trait("courage"));
                v.Add(V("Desirability", Scaled(e, m, -10, 0.6f, (0.4f, trust)), "-"));
                // The cruel see raiding as the game; an attack by someone trusted is a moral offence.
                v.Add(V("Praiseworthiness", Scaled(e, m, -10, 0.5f, (-0.5f, cruelty), (0.5f, trust)), "[x]"));
                v.Add(V("Like", Scaled(e, m, -10, 0.1f, (0.6f, vind)), "-"));
                v.Add(V(GSP, Scaled(e, m, -0.6f, 0.4f, (0.6f, fear), (-0.2f, courage)), "Safe(SELF)"));
            });

            Rule("Threaten", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var fear = e.Bind(Rel("Fear"));
                var freedom = e.Bind(Trait("freedom")); var courage = e.Bind(Trait("courage"));
                v.Add(V("Desirability", Scaled(e, m, -10, 0.2f, (0.4f, freedom)), "-"));
                v.Add(V("Praiseworthiness", Scaled(e, m, -10, 0f, (0.5f, freedom), (0.5f, courage)), "[x]"));
                v.Add(V(GSP, Scaled(e, m, -1f, 0.4f, (0.6f, fear)), "Safe(SELF)"));
            });

            Rule("OfferPact", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust")); var respect = e.Bind(Rel("Respect"));
                var loyalty = e.Bind(Trait("loyalty")); var freedom = e.Bind(Trait("freedom"));
                v.Add(V("Desirability", Scaled(e, m, 10, 0.2f, (0.4f, trust), (0.4f, loyalty), (-0.3f, freedom)), "-"));
                v.Add(V("Praiseworthiness", Scaled(e, m, 10, 0.1f, (0.4f, respect), (0.3f, trust)), "[x]"));
                v.Add(V(GSP, Scaled(e, m, 0.25f, 1f), "Safe(SELF)"));
            });

            Rule("KeepPact", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust")); var liking = e.Bind(Rel("Liking"));
                var loyalty = e.Bind(Trait("loyalty")); var honesty = e.Bind(Trait("honesty"));
                v.Add(V("Desirability", Scaled(e, m, 10, 0.3f, (0.4f, loyalty), (0.2f, trust)), "-"));
                v.Add(V("Praiseworthiness", Scaled(e, m, 10, 0.1f, (0.8f, honesty)), "[x]"));
                v.Add(V("Like", Scaled(e, m, 10, 0.1f, (0.4f, trust), (0.4f, liking)), "-"));
                v.Add(V(GSP, Scaled(e, m, 0.3f, 1f), "Safe(SELF)"));
            });

            Rule("DemandTribute", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var fear = e.Bind(Rel("Fear")); var respect = e.Bind(Rel("Respect"));
                var freedom = e.Bind(Trait("freedom")); var authority = e.Bind(Trait("authority"));
                v.Add(V("Desirability", Scaled(e, m, -10, 0.3f, (0.7f, freedom)), "-"));
                // Hierarchy-respecters accept tribute to a lord they respect; free spirits resent it.
                v.Add(V("Praiseworthiness", Scaled(e, m, -10, 0.6f, (-0.5f, authority), (-0.3f, respect), (0.4f, freedom)), "[x]"));
                v.Add(V(GSP, Scaled(e, m, -0.8f, 0.2f, (0.8f, fear)), "Safe(SELF)"));
            });

            Rule("Coup", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust"));
                var freedom = e.Bind(Trait("freedom")); var authority = e.Bind(Trait("authority"));
                var loyalty = e.Bind(Trait("loyalty")); var ambition = e.Bind(Trait("ambition"));
                // Signed by values: the free and ambitious welcome an overthrow, the loyal and obedient do not.
                v.Add(V("Desirability", Scaled(e, m, 10, 0f, (0.6f, freedom), (-0.6f, authority), (-0.3f, loyalty), (0.2f, ambition)), "-"));
                v.Add(V("Praiseworthiness", Scaled(e, m, 10, -0.1f, (0.4f, ambition), (0.3f, freedom), (-0.6f, loyalty), (0.2f, trust)), "[x]"));
                v.Add(V(GSP, Scaled(e, m, -0.4f, 0f, (1f, loyalty)), "Safe(SELF)"));
            });

            Rule("Leak", (e, v) =>
            {
                var m = e.Bind(Rel("Magnitude"));
                var trust = e.Bind(Rel("Trust"));
                var honesty = e.Bind(Trait("honesty")); var forgiveness = e.Bind(Trait("forgiveness"));
                var courage = e.Bind(Trait("courage"));
                v.Add(V("Desirability", Scaled(e, m, -10, 0.1f, (0.6f, trust)), "-"));
                v.Add(V("Praiseworthiness", Scaled(e, m, -10, 0.1f, (0.8f, honesty)), "[x]"));
                v.Add(V("Like", Scaled(e, m, -10, 0.4f, (-0.3f, forgiveness)), "-"));
                v.Add(V(GSP, Scaled(e, m, -0.3f, 1f, (-0.6f, courage)), "Safe(SELF)"));
            });
        }

        // Layer `Belief`: after each perceived event the character decides how its relationship beliefs move.
        // new = cur + m * rate * (goal - cur), rate = base + w * trait, so beliefs stay in 0..1.
        static void AuthorRelationshipUpdates(EmotionalDecisionMaking.EmotionalDecisionMakingAsset edm)
        {
            var table = new (string Action, string Rel, float Goal, float Base, string Trait, float W)[]
            {
                ("Betray", "Trust", 0, 0.75f, "forgiveness", -0.35f),
                ("Betray", "Liking", 0, 0.3f, "vindictiveness", 0.5f),
                ("Betray", "Respect", 0, 0.2f, "honesty", 0.4f),
                ("Betray", "Fear", 1, 0.25f, "courage", -0.2f),
                ("Aid", "Trust", 1, 0.15f, "loyalty", 0.2f),
                ("Aid", "Liking", 1, 0.2f, "generosity", 0.2f),
                ("Aid", "Debt", 1, 0.25f, "honesty", 0.4f),
                ("Attack", "Trust", 0, 0.35f, "forgiveness", -0.2f),
                ("Attack", "Liking", 0, 0.15f, "vindictiveness", 0.4f),
                ("Attack", "Fear", 1, 0.45f, "courage", -0.4f),
                ("Attack", "Respect", 1, 0.05f, "authority", 0.25f),
                ("Threaten", "Fear", 1, 0.35f, "courage", -0.3f),
                ("Threaten", "Liking", 0, 0.1f, "freedom", 0.25f),
                ("Threaten", "Trust", 0, 0.15f, "forgiveness", -0.1f),
                ("OfferPact", "Trust", 1, 0.05f, "loyalty", 0.15f),
                ("OfferPact", "Liking", 1, 0.1f, "generosity", 0.1f),
                ("KeepPact", "Trust", 1, 0.2f, "honesty", 0.25f),
                ("KeepPact", "Respect", 1, 0.1f, "honesty", 0.15f),
                ("DemandTribute", "Liking", 0, 0.15f, "freedom", 0.35f),
                ("DemandTribute", "Fear", 1, 0.2f, "courage", -0.2f),
                ("DemandTribute", "Respect", 1, 0.0f, "authority", 0.3f),
                ("Coup", "Respect", 1, 0.05f, "ambition", 0.35f),
                ("Coup", "Trust", 0, 0.1f, "loyalty", 0.45f),
                ("Leak", "Trust", 0, 0.3f, "honesty", 0.3f),
                ("Leak", "Respect", 0, 0.1f, "honesty", 0.25f),
            };

            foreach (var r in table)
            {
                var e = new Expr("b");
                e.Raw("Focus(SELF) = [x]");
                e.Raw($"Stimulus(SELF, [x]) = {r.Action}");
                var m = e.Bind(Rel("Magnitude"));
                var cur = e.Bind(Rel(r.Rel));
                var trait = e.Bind(Trait(r.Trait));
                var rate = e.Add(e.Mul(trait, r.W), r.Base);
                var gap = e.Op(F(r.Goal), "Minus", cur);
                var step = e.Op(e.Op(gap, "Times", rate), "Times", m);
                var next = e.Op(cur, "Plus", step);

                // Conditions go in through the DTO: AddRuleCondition prepends, and Math must see its inputs bound
                // by the conditions before it.
                edm.AddActionRule(new ActionRuleDTO
                {
                    Action = Name.BuildName($"Believe({r.Rel}, {next})"),
                    Target = Name.BuildName("[x]"),
                    Priority = Name.BuildName("1"),
                    Layer = Name.BuildName("Belief"),
                    Conditions = new ConditionSetDTO { ConditionSet = e.Conditions.ToArray() },
                });
            }
        }

        // ------------------------------------------------------------------ Comme il Faut

        // (mode "*", value, conditions). All conditions of one rule must hold for its value to count.
        static (string Name, string Description, string[] Start, (int, string[])[] Rules)[] Exchanges()
        {
            string T(string trait, string op, float v) => $"{Trait(trait)} {op} {F(v)}";
            string R(string rel, string op, float v) => $"{Rel(rel)} {op} {F(v)}";
            string E(string emotion, string op, float v) => $"EmotionIntensity(SELF, {emotion}) {op} {F(v)}";
            const string Always = "Focus(SELF) = [x]";

            return new[]
            {
                ("Ignore", "Do nothing towards this player", new[] { Always }, new (int, string[])[]
                {
                    (2, new[] { Always }),
                }),
                ("OfferPact", "Propose a public pact", new[] { "Pact(SELF, [x]) = False" }, new (int, string[])[]
                {
                    (3, new[] { R("Trust", ">=", 0.6f) }), (2, new[] { R("Trust", ">=", 0.4f) }),
                    (2, new[] { T("loyalty", ">=", 0.6f) }), (1, new[] { R("Liking", ">=", 0.6f) }),
                    (2, new[] { R("Fear", ">=", 0.6f), T("courage", "<", 0.5f) }),
                    (2, new[] { "SI([x]) >= 6" }),
                    (-3, new[] { T("freedom", ">=", 0.85f) }), (-3, new[] { R("Trust", "<", 0.25f) }),
                    (-3, new[] { E("Anger", ">=", 3) }), (-2, new[] { E("Hate", ">=", 2) }),
                }),
                ("RefusePact", "Refuse a pact this player offered", new[] { "Offered(SELF, [x]) = True" }, new (int, string[])[]
                {
                    (3, new[] { R("Trust", "<", 0.3f) }), (2, new[] { T("freedom", ">=", 0.8f) }),
                    (2, new[] { T("cunning", ">=", 0.7f), R("Trust", "<", 0.5f) }),
                    (3, new[] { E("Anger", ">=", 3) }), (2, new[] { E("Hate", ">=", 2) }),
                    (-3, new[] { R("Trust", ">=", 0.6f) }), (-2, new[] { R("Fear", ">=", 0.6f) }),
                }),
